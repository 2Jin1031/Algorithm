SELECT 
    Y AS YEAR, 
    M - SIZE_OF_COLONY
    AS YEAR_DEV,
    ed1.ID AS ID
FROM ECOLI_DATA AS ed1 
    JOIN (
        SELECT YEAR(DIFFERENTIATION_DATE) AS Y, MAX(SIZE_OF_COLONY) AS M
        FROM ECOLI_DATA
        GROUP BY YEAR(DIFFERENTIATION_DATE)
        ) AS ed2
    ON YEAR(ed1.DIFFERENTIATION_DATE) = Y
ORDER BY Y, YEAR_DEV